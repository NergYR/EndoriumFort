const I18nContext = createContext(null);

const getValue = (object, path) => path.split('.').reduce((acc, key) => (acc == null ? acc : acc[key]), object);

const interpolate = (template, params = {}) =>
  String(template).replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));

const resolveInitialLocale = () => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'fr' || saved === 'en') return saved;
  } catch (_) {}
  if (typeof navigator !== 'undefined') {
    const browserLocale = String(navigator.language || '').toLowerCase();
    if (browserLocale.startsWith('fr')) return 'fr';
    if (browserLocale.startsWith('en')) return 'en';
  }
  return DEFAULT_LOCALE;
};

export function I18nProvider({ children }) {
  const [locale, setLocale] = useState(resolveInitialLocale);

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch (_) {}
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo(() => {
    const t = (key, params = {}) => {
      const entry = getValue(translations[locale], key) ?? getValue(translations.en, key) ?? key;
      if (typeof entry === 'function') {
        return entry(params, locale);
      }
      if (Array.isArray(entry)) return entry;
      return interpolate(entry, params);
    };

    const raw = (key) => getValue(translations[locale], key) ?? getValue(translations.en, key);

    return { locale, setLocale, t, raw };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return value;
}
